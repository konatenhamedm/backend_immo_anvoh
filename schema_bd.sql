-- ============================================================================
-- BASE DE DONNÉES THIEBBRO IMMO (PropTech Côte d'Ivoire)
-- Schéma relationnel PostgreSQL / Django
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. TABLE : users_user (Comptes & Utilisateurs)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password VARCHAR(128) NOT NULL,
    last_login TIMESTAMPTZ NULL,
    is_superuser BOOLEAN NOT NULL DEFAULT FALSE,
    first_name VARCHAR(150) NOT NULL,
    last_name VARCHAR(150) NOT NULL,
    is_staff BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    date_joined TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone_number VARCHAR(30) NOT NULL,
    country_of_residence VARCHAR(100) NOT NULL DEFAULT 'Côte d''Ivoire',
    is_diaspora BOOLEAN NOT NULL DEFAULT FALSE,
    role VARCHAR(20) NOT NULL DEFAULT 'PARTICULIER', -- PARTICULIER, INVESTISSEUR, PROPRIETAIRE, PROMOTEUR, AGENT, ADMIN
    project_objective VARCHAR(30) NULL,             -- HABITER, INVESTIR, LOUER, AUTRE
    project_budget NUMERIC(14, 2) NULL,
    project_down_payment NUMERIC(14, 2) NULL,
    project_zone VARCHAR(150) NOT NULL DEFAULT '',
    project_timeframe VARCHAR(30) NULL,             -- IMMEDIAT, 0_3_MOIS, 3_6_MOIS, 6_12_MOIS, PLUS_TARD
    notifications_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_email ON users_user(email);
CREATE INDEX IF NOT EXISTS idx_users_role ON users_user(role);

-- ----------------------------------------------------------------------------
-- 2. TABLE : properties_developmentproject (Programmes Neufs)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS properties_developmentproject (
    id UUID PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL UNIQUE,
    developer_name VARCHAR(150) NOT NULL,
    city VARCHAR(100) NOT NULL DEFAULT 'Abidjan',
    commune VARCHAR(100) NOT NULL,
    neighborhood VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    total_lots_count INTEGER NOT NULL DEFAULT 1 CHECK (total_lots_count >= 0),
    delivery_date VARCHAR(100) NOT NULL DEFAULT '',
    starting_price NUMERIC(14, 2) NOT NULL,
    cover_image VARCHAR(100) NULL,
    brochure_pdf VARCHAR(100) NULL,
    virtual_tour_url VARCHAR(200) NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_devproject_commune ON properties_developmentproject(commune);
CREATE INDEX IF NOT EXISTS idx_devproject_featured ON properties_developmentproject(is_featured);

-- ----------------------------------------------------------------------------
-- 3. TABLE : properties_projectlot (Lots d'un Programme)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS properties_projectlot (
    id UUID PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES properties_developmentproject(id) ON DELETE CASCADE,
    lot_number VARCHAR(50) NOT NULL,
    typology VARCHAR(20) NOT NULL DEFAULT 'F3', -- F1, F2, F3, F4, F5, AUTRE
    building_name VARCHAR(50) NOT NULL DEFAULT '',
    floor INTEGER NOT NULL DEFAULT 0,
    surface_sqm NUMERIC(8, 2) NOT NULL,
    price NUMERIC(14, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE' -- DISPONIBLE, OPTION, RESERVE, VENDU, ARCHIVE
);

CREATE INDEX IF NOT EXISTS idx_projectlot_project ON properties_projectlot(project_id);
CREATE INDEX IF NOT EXISTS idx_projectlot_status ON properties_projectlot(status);

-- ----------------------------------------------------------------------------
-- 4. TABLE : properties_property (Biens Immobiliers)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS properties_property (
    id UUID PRIMARY KEY,
    reference VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    property_type VARCHAR(30) NOT NULL, -- APPARTEMENT, VILLA, MAISON, DUPLEX, TERRAIN, IMMEUBLE, RESIDENCE_MEUBLEE, BUREAU, COMMERCIAL
    typology VARCHAR(20) NOT NULL DEFAULT 'F3',
    target_goal VARCHAR(20) NOT NULL DEFAULT 'MIXTE', -- HABITATION, INVESTISSEMENT, MIXTE, LOCATION
    status VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    verification_status VARCHAR(30) NOT NULL DEFAULT 'EN_ATTENTE', -- NON_VERIFIE, EN_ATTENTE, VERIFIE, VERIFICATION_RENFORCEE
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_selected_investment BOOLEAN NOT NULL DEFAULT FALSE,
    price NUMERIC(14, 2) NOT NULL,
    recommended_down_payment NUMERIC(14, 2) NULL,
    estimated_monthly_rent NUMERIC(12, 2) NULL,
    estimated_yield_rate NUMERIC(5, 2) NULL,
    investment_score INTEGER NOT NULL DEFAULT 75 CHECK (investment_score >= 0),
    city VARCHAR(100) NOT NULL DEFAULT 'Abidjan',
    commune VARCHAR(100) NOT NULL,
    neighborhood VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL DEFAULT '',
    latitude NUMERIC(9, 6) NULL,
    longitude NUMERIC(9, 6) NULL,
    surface_sqm NUMERIC(8, 2) NOT NULL,
    rooms_count INTEGER NOT NULL DEFAULT 3 CHECK (rooms_count >= 0),
    bedrooms_count INTEGER NOT NULL DEFAULT 2 CHECK (bedrooms_count >= 0),
    bathrooms_count INTEGER NOT NULL DEFAULT 2 CHECK (bathrooms_count >= 0),
    has_parking BOOLEAN NOT NULL DEFAULT FALSE,
    has_swimming_pool BOOLEAN NOT NULL DEFAULT FALSE,
    has_elevator BOOLEAN NOT NULL DEFAULT FALSE,
    has_security BOOLEAN NOT NULL DEFAULT FALSE,
    has_generator BOOLEAN NOT NULL DEFAULT FALSE,
    has_green_space BOOLEAN NOT NULL DEFAULT FALSE,
    video_url VARCHAR(200) NULL,
    virtual_tour_url VARCHAR(200) NULL,
    assigned_agent_id BIGINT NULL REFERENCES users_user(id) ON DELETE SET NULL,
    development_project_id UUID NULL REFERENCES properties_developmentproject(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_property_reference ON properties_property(reference);
CREATE INDEX IF NOT EXISTS idx_property_commune ON properties_property(commune);
CREATE INDEX IF NOT EXISTS idx_property_status ON properties_property(status);
CREATE INDEX IF NOT EXISTS idx_property_price ON properties_property(price);
CREATE INDEX IF NOT EXISTS idx_property_type ON properties_property(property_type);

-- ----------------------------------------------------------------------------
-- 5. TABLE : properties_propertyimage (Galerie Médias)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS properties_propertyimage (
    id UUID PRIMARY KEY,
    property_id UUID NOT NULL REFERENCES properties_property(id) ON DELETE CASCADE,
    image VARCHAR(100) NOT NULL,
    caption VARCHAR(150) NOT NULL DEFAULT '',
    is_cover BOOLEAN NOT NULL DEFAULT FALSE,
    "order" INTEGER NOT NULL DEFAULT 0 CHECK ("order" >= 0)
);

CREATE INDEX IF NOT EXISTS idx_propimage_property ON properties_propertyimage(property_id);

-- ----------------------------------------------------------------------------
-- 6. TABLE : properties_propertyfavorite (Favoris Utilisateurs)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS properties_propertyfavorite (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users_user(id) ON DELETE CASCADE,
    property_id UUID NOT NULL REFERENCES properties_property(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_property_favorite UNIQUE (user_id, property_id)
);

CREATE INDEX IF NOT EXISTS idx_favorite_user ON properties_propertyfavorite(user_id);
CREATE INDEX IF NOT EXISTS idx_favorite_property ON properties_propertyfavorite(property_id);

-- ----------------------------------------------------------------------------
-- 7. TABLE : crm_lead (Prospects CRM & Pipeline Kanban)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_lead (
    id UUID PRIMARY KEY,
    user_id BIGINT NULL REFERENCES users_user(id) ON DELETE SET NULL,
    full_name VARCHAR(200) NOT NULL,
    phone_number VARCHAR(30) NOT NULL,
    whatsapp_number VARCHAR(30) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL DEFAULT '',
    country_of_residence VARCHAR(100) NOT NULL DEFAULT 'Côte d''Ivoire',
    is_diaspora BOOLEAN NOT NULL DEFAULT FALSE,
    objective VARCHAR(100) NOT NULL DEFAULT '',
    property_type VARCHAR(100) NOT NULL DEFAULT '',
    preferred_zone VARCHAR(150) NOT NULL DEFAULT '',
    budget NUMERIC(14, 2) NULL,
    down_payment NUMERIC(14, 2) NULL,
    timeframe VARCHAR(100) NOT NULL DEFAULT '',
    consulted_property_id UUID NULL REFERENCES properties_property(id) ON DELETE SET NULL,
    source VARCHAR(40) NOT NULL DEFAULT 'APPLICATION',
    stage VARCHAR(30) NOT NULL DEFAULT 'NOUVEAU', -- NOUVEAU, CONTACTE, QUALIFIE, RDV, VISITE, PROPOSITION, NEGOCIATION, RESERVATION, VENTE, PERDU
    score INTEGER NOT NULL DEFAULT 20 CHECK (score >= 0),
    temperature VARCHAR(20) NOT NULL DEFAULT 'FROID', -- FROID, TIEDE, CHAUD, TRES_CHAUD
    assigned_agent_id BIGINT NULL REFERENCES users_user(id) ON DELETE SET NULL,
    last_interaction_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_action VARCHAR(255) NOT NULL DEFAULT '',
    commercial_notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_lead_stage ON crm_lead(stage);
CREATE INDEX IF NOT EXISTS idx_lead_score ON crm_lead(score);
CREATE INDEX IF NOT EXISTS idx_lead_agent ON crm_lead(assigned_agent_id);

-- ----------------------------------------------------------------------------
-- 8. TABLE : crm_crminteraction (Journal des Interactions)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_crminteraction (
    id UUID PRIMARY KEY,
    lead_id UUID NOT NULL REFERENCES crm_lead(id) ON DELETE CASCADE,
    interaction_type VARCHAR(50) NOT NULL, -- WHATSAPP_CLICK, INQUIRY, CALL, NOTE, EMAIL
    details TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_interaction_lead ON crm_crminteraction(lead_id);

-- ----------------------------------------------------------------------------
-- 9. TABLE : crm_propertyinquiry (Demandes d'Information)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_propertyinquiry (
    id UUID PRIMARY KEY,
    property_id UUID NOT NULL REFERENCES properties_property(id) ON DELETE CASCADE,
    lead_id UUID NOT NULL REFERENCES crm_lead(id) ON DELETE CASCADE,
    user_id BIGINT NULL REFERENCES users_user(id) ON DELETE SET NULL,
    objective VARCHAR(100) NOT NULL,
    message TEXT NOT NULL DEFAULT '',
    is_processed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inquiry_property ON crm_propertyinquiry(property_id);
CREATE INDEX IF NOT EXISTS idx_inquiry_lead ON crm_propertyinquiry(lead_id);

-- ----------------------------------------------------------------------------
-- 10. TABLE : crm_visitrequest (Demandes de Visite / RDV)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_visitrequest (
    id UUID PRIMARY KEY,
    property_id UUID NOT NULL REFERENCES properties_property(id) ON DELETE CASCADE,
    lead_id UUID NOT NULL REFERENCES crm_lead(id) ON DELETE CASCADE,
    user_id BIGINT NULL REFERENCES users_user(id) ON DELETE SET NULL,
    visit_type VARCHAR(20) NOT NULL DEFAULT 'PHYSIQUE', -- PHYSIQUE, VISIO
    status VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE',    -- EN_ATTENTE, CONFIRMEE, EFFECTUEE, ANNULEE
    scheduled_date DATE NOT NULL,
    scheduled_time TIME NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_visit_property ON crm_visitrequest(property_id);
CREATE INDEX IF NOT EXISTS idx_visit_lead ON crm_visitrequest(lead_id);
CREATE INDEX IF NOT EXISTS idx_visit_status ON crm_visitrequest(status);
